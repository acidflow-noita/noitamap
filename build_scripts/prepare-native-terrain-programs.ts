/** Development-time snapshot of pinned, corrected arithmetic. Browser runtime
 * imports only the resulting owned shader modules, never Telescope's renderer.
 * Run with node --import tsx build_scripts/prepare-native-terrain-programs.ts. */
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { standaloneTerrainShaders } from './vite-terrain-shaders';

const module = standaloneTerrainShaders(resolve('lib/noita-telescope-vm/js'));
const { TERRAIN_FS: source, TERRAIN_VS: vertex } = new Function(
  module.replace(/export (?=const |function )/g, '') + '\nreturn { TERRAIN_FS, TERRAIN_VS };',
)();
const main = source.indexOf('void main() {');
const engine = source.indexOf('    if (u_engineTerrain) {', main);
const resolveStart = source.indexOf('        // Noitamap: resolve once for color and material-id output.', engine);
const legacy = source.indexOf('    ivec2 pos;', resolveStart);
if ([main, engine, resolveStart, legacy].some(n => n < 0)) throw Error('Terrain source boundary changed');
const declarations = source.slice(0, main);
const coordinates = source.slice(main, engine);
const initialization = source.slice(engine + '    if (u_engineTerrain) {\n'.length, resolveStart);
const extras = `
uniform highp usampler2D u_nativeRaw;
uniform highp usampler2D u_nativeProbeIds;
uniform bool u_nativeProbe;
int nativeMaterial(highp usampler2D ids) {
    return int(texelFetch(ids, ivec2(gl_FragCoord.xy), 0).r) - 1;
}
`;

// Remove unreachable functions before driver compilation, retaining expressions
// verbatim. Source arithmetic order is part of the numeric compatibility contract.
function reachable(glsl: string): string {
  const functions = new Map<string, { start: number; end: number; text: string }>();
  for (const match of glsl.matchAll(/^(?:void|bool|int|uint|float|[iu]?vec[234])\s+(\w+)\([^;{]*\)\s*\{/gm)) {
    let end = match.index! + match[0].length, depth = 1;
    while (depth && end < glsl.length) {
      const c = glsl[end++];
      if (c === '{') depth++; else if (c === '}') depth--;
    }
    functions.set(match[1], { start: match.index!, end, text: glsl.slice(match.index, end) });
  }
  const used = new Set<string>();
  const visit = (name: string) => {
    if (used.has(name)) return;
    used.add(name);
    for (const match of (functions.get(name)?.text ?? '').matchAll(/\b(\w+)\s*\(/g))
      if (functions.has(match[1])) visit(match[1]);
  };
  visit('main');
  for (const [name, fn] of [...functions].reverse())
    if (!used.has(name)) glsl = glsl.slice(0, fn.start) + glsl.slice(fn.end);
  return glsl;
}

function material(topology: 0 | 2): string {
  return reachable(declarations.replace('out vec4 outColor;', 'layout(location = 0) out highp uint nativeId;') + extras
    + coordinates.replace('outColor = vec4(0.0);', 'nativeId = 0u;') + `
    if (u_nativeProbe) {
        // Only air below a levelled pool needs a second procedural sample.
        if (nativeMaterial(u_nativeRaw) != 0) discard;
        ivec3 liquid = nmLiquidSurface(w);
        if (liquid.y == 0 || w.y < liquid.x || !nmLiquidOwned(ivec2(w.x, liquid.z))) discard;
        w.y = liquid.z;
    }
${initialization}
    int mat = -1;
    if ((info & 2048u) != 0u) mat = 0;
    else if (mode == ${topology === 2 ? 1 : 0}u) {
        int slot = int(info & 0xffu);
        ${topology === 2 ? 'mat = engTopo2(slot, w);' : `
        int pcx = fdiv(w.x + u_centerPx, CHUNK), pcy = fdiv(w.y + u_baseY, CHUNK);
        int physSlot = int(engInfoAt(pcx, pcy) & 0xffu);
        int leftSlot = int(engInfoAt(pcx - 1, pcy) & 0xffu);
        mat = engTopo0(slot, physSlot, leftSlot, w);`}
        if (mat == -2) mat = engBandSelect(slot, w, nmBandDensity);
        if (mat < 0) mat = 0;
    } else discard;
    nativeId = uint(mat + 1);
}
`);
}
const color = reachable(declarations + extras + coordinates + `
    if (u_engineTerrain) {
        int mat = nativeMaterial(u_nativeRaw);
        if (u_materialIdOut) {
            int code = mat + 1;
            outColor = vec4(float(code & 255) / 255.0, float((code >> 8) & 255) / 255.0, 0.0, 1.0);
            return;
        }
        ivec3 liquid = nmLiquidSurface(w);
        if (liquid.y != 0 && (mat == 0 || mat == liquid.y)) {
            if (w.y < liquid.x) mat = 0;
            else if (mat == 0 && nmLiquidOwned(ivec2(w.x, liquid.z)))
                mat = nativeMaterial(u_nativeProbeIds) == liquid.y ? liquid.y : 0;
        }
        if (mat >= 0) {
            if (mat > 0) engMaterialColor(mat, w);
            return;
        }
    }
` + source.slice(legacy));
const programs = { vertex, topology0: material(0), topology2: material(2), color };
const directory = resolve('src/native-map/gpu');
await mkdir(directory, { recursive: true });
await writeFile(resolve(directory, 'terrain-programs.ts'), `// Generated by build_scripts/prepare-native-terrain-programs.ts; see PROVENANCE.txt.\n// Corrected reference SHA256: ${createHash('sha256').update(source).digest('hex')}\n` +
  Object.entries(programs).map(([name, code]) => `export const ${name} = ${JSON.stringify(code)};\n`).join(''));
console.log('[Native terrain programs]', Object.fromEntries(Object.entries(programs).map(([name, code]) => [name, code.length])));
