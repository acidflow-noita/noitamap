// ---------------------------------------------------------------------------
// Pixel scene bitmap cache (PERF_PLAN Step 1)
//
// Each recolored variant is uploaded once as an ImageBitmap plus a mip chain
// (1/2 .. 1/16). The draw site picks a level from the camera zoom, so a zoomed-out
// frame blits a handful of pixels per scene instead of a full-resolution image, which
// is what made drawing them at low zoom expensive enough to gate off entirely.
//
// The raw recolored Uint8Array is released once its bitmap exists (the overlay worker
// recolors from the untouched base image, so any variant can be produced again). Entries
// are evicted least-recently-drawn first over a byte budget; an evicted variant is
// re-requested from the overlay worker through the rebuild hook below.
// ---------------------------------------------------------------------------
export const PIXEL_SCENE_MAX_MIP = 4; // 1/2, 1/4, 1/8, 1/16
const PIXEL_SCENE_BITMAP_CACHE = new Map(); // `${key}/${variantKey}` -> entry
let pixelSceneCacheBytes = 0;
let pixelSceneDrawTick = 0;

// Left in place of a released Uint8Array so the "do we already have this variant?" checks
// in overlay_manager / world_manager don't re-request it while its bitmap is still alive.
const VARIANT_RELEASED = { released: true };

// ---------------------------------------------------------------------------
// Bitmaps are BUILT IN THE OVERLAY WORKER, never on this thread.
//
// Turning a scene's pixels into a drawable used to happen synchronously on the
// first draw that needed it: recolor -> visual-art overlay -> putImageData ->
// transferToImageBitmap, then a GPU readback + JS halving for every mip level,
// and for a textured instance a full per-pixel material build on top. That was
// 30-110 ms for one large scene scrolling into view and a 50 ms frame at the
// overview zoom -- the worst frames the renderer had once the tooltip readback
// was gone. Now a cache miss posts a BUILD_SCENE_BITMAPS request (through the
// hook overlay_manager registers below) and returns nothing to draw; the worker
// answers with the finished ImageBitmap chain, which lands here through
// putPixelSceneBitmaps(). The scene is missing for the frames in between, which
// drawNow hides by warming scenes in a margin around the view before they are
// visible (warmPixelScene).
//
// A textured instance that is still being built draws its FLAT variant meanwhile
// (same key without the position), so crossing the texture zoom shows a flat
// scene that sharpens rather than a hole.
// ---------------------------------------------------------------------------
let sceneBitmapRequester = null;   // (request, sceneData) => void, set by overlay_manager
const pendingSceneBitmaps = new Map();   // cacheKey -> textured (in flight at the worker)
// Cumulative, for the Render HUD. A refetch is a request for a key that was
// already delivered once -- evicted and wanted back, the signature of thrash.
const sceneBitmapCounters = { requests: 0, refetches: 0, evictions: 0, failures: 0 };
const deliveredSceneBitmaps = new Set();
// Bumped whenever the cache is cleared, so a reply for the old contents is dropped.
let sceneBitmapEpoch = 0;
// In-flight caps. The worker is FIFO and cannot cancel: with no cap a pan at the
// textured zoom would queue every instance it passed over (each a 30-110 ms
// build) ahead of the ones actually on screen. Misses past the cap are simply
// asked again on the next draw, which is what keeps requests tracking the view.
const MAX_INFLIGHT_TEXTURED = 6;
const MAX_INFLIGHT_FLAT = 48;

export function setPixelSceneBitmapRequester(fn) {
	sceneBitmapRequester = fn;
}

/** Scene bitmaps asked of the worker and not back yet (the harness waits on it). */
export function pendingPixelSceneBitmaps() {
	return pendingSceneBitmaps.size;
}

function requestSceneBitmaps(pixelScene, cacheKey, textured) {
	if (!sceneBitmapRequester || pendingSceneBitmaps.has(cacheKey)) return;
	const data = PIXEL_SCENE_DATA[pixelScene.key];
	if (!data) return;
	let inflight = 0;
	for (const t of pendingSceneBitmaps.values()) if (t === textured) inflight++;
	// Render Everything asks for a textured build of every visible instance at
	// any zoom (~1150 at the overview); at the normal cap that trickles in over
	// a minute, so let the worker run flat out there. Its whole point is a
	// zoom-independent frame, not a responsive one.
	const texturedCap = appSettings.renderEverything ? 32 : MAX_INFLIGHT_TEXTURED;
	if (inflight >= (textured ? texturedCap : MAX_INFLIGHT_FLAT)) return;
	pendingSceneBitmaps.set(cacheKey, textured);
	sceneBitmapCounters.requests++;
	if (deliveredSceneBitmaps.has(cacheKey)) sceneBitmapCounters.refetches++;
	sceneBitmapRequester({
		cmd: 'BUILD_SCENE_BITMAPS',
		epoch: sceneBitmapEpoch,
		cacheKey,
		key: pixelScene.key,
		variantKey: pixelScene.variantKey || '',
		x: pixelScene.x,
		y: pixelScene.y,
		textured,
		erase: !textured && cacheKey.endsWith(FLAT_ERASE_SUFFIX),
		texturedAlphas: !textured && cacheKey.endsWith(FLAT_ERASE_SUFFIX) ? texturedFlatAlphas() : null,
		maxLevel: sceneMaxMipLevel(data.width, data.height),
	}, data);
}

/**
 * Accepts a finished bitmap chain from the worker (overlay_manager routes the
 * SCENE_BITMAPS reply here). Returns true when something new is drawable.
 */
// Bumped whenever a drawable scene appears or disappears, so a caller that
// composites many scenes into one bitmap (app.js sceneBake) knows to rebuild.
let sceneBitmapVersion = 0;
export function pixelSceneBitmapVersion() {
	return sceneBitmapVersion;
}

export function putPixelSceneBitmaps(msg) {
	pendingSceneBitmaps.delete(msg.cacheKey);
	sceneBitmapVersion++;
	const bitmaps = [...(msg.levels || []), ...(msg.airMasks || [])].filter(Boolean);
	if (msg.epoch !== sceneBitmapEpoch || !msg.levels || !msg.levels[0]) {
		for (const b of bitmaps) b.close?.();
		if (msg.epoch === sceneBitmapEpoch) logSceneBitmapFailure(msg);
		return false;
	}
	const old = PIXEL_SCENE_BITMAP_CACHE.get(msg.cacheKey);
	if (old) releasePixelSceneEntry(old);
	const entry = {
		cacheKey: msg.cacheKey,
		width: msg.width,
		height: msg.height,
		levels: new Array(PIXEL_SCENE_MAX_MIP + 1).fill(null),
		maxLevel: msg.levels.length - 1,
		airMasks: msg.airMasks || [],   // per level, alongside `levels`
		bytes: 0,
		// As recent as anything drawn: it was asked for because it is on (or
		// about to be on) screen. At 0 it was the LRU minimum, so with the cache
		// full every arrival was evicted by the next draw before it was ever
		// drawn, and re-requested -- a build loop that never showed the scene.
		used: ++pixelSceneDrawTick,
	};
	for (let l = 0; l < msg.levels.length; l++) addPixelSceneBitmap(entry, l, msg.levels[l]);
	for (const m of entry.airMasks) {
		if (!m) continue;
		const bytes = m.width * m.height * 4;
		entry.bytes += bytes;
		pixelSceneCacheBytes += bytes;
	}
	PIXEL_SCENE_BITMAP_CACHE.set(entry.cacheKey, entry);
	deliveredSceneBitmaps.add(entry.cacheKey);
	// The bitmap is now the only copy this thread needs of a biome-recolored
	// variant: material lookups (utils.js) read the pre-biome variants, which are
	// left alone, and the worker rebuilds any variant from the base image.
	const data = PIXEL_SCENE_DATA[msg.key];
	if (!msg.textured && data?.variants && msg.variantKey.includes('biome=')
		&& ArrayBuffer.isView(data.variants[msg.variantKey])) {
		data.variants[msg.variantKey] = VARIANT_RELEASED;
	}
	return true;
}

// A failed build caches nothing, so the next draw asks again: a scene that
// always fails is re-requested every frame it is in view. Count per key so
// that loop is visible in the console without flooding it.
const sceneBitmapFailures = new Map();   // cacheKey -> count
function logSceneBitmapFailure(msg) {
	const n = (sceneBitmapFailures.get(msg.cacheKey) || 0) + 1;
	sceneBitmapFailures.set(msg.cacheKey, n);
	sceneBitmapCounters.failures++;
	if (n <= 3 || n % 50 === 0) {
		const data = PIXEL_SCENE_DATA[msg.key];
		console.error(`[scene bitmaps] worker returned no bitmap for ${msg.cacheKey}${msg.textured ? ' (tex)' : ''}`
			+ ` (failure #${n}${n > 1 ? ', re-request loop' : ''}): ${msg.failReason ?? 'no reason given'}`,
			{ msg, mainThreadImg: data?.imgElement?.constructor?.name, variant: data?.variants?.[msg.variantKey],
				epoch: sceneBitmapEpoch, pending: pendingSceneBitmaps.size, cacheEntries: PIXEL_SCENE_BITMAP_CACHE.size });
	}
}

/** Halving stops once either axis would round to nothing. */
export function sceneMaxMipLevel(width, height) {
	return Math.min(PIXEL_SCENE_MAX_MIP, Math.floor(Math.log2(Math.max(1, Math.min(width, height)))));
}

export function getPixelSceneCacheStats() {
	let pendingTextured = 0;
	for (const t of pendingSceneBitmaps.values()) if (t) pendingTextured++;
	return {
		entries: PIXEL_SCENE_BITMAP_CACHE.size, bytes: pixelSceneCacheBytes, budgetBytes: sceneBitmapBudgetBytes(),
		pending: pendingSceneBitmaps.size, pendingTextured, ...sceneBitmapCounters,
	};
}

function releasePixelSceneEntry(entry) {
	for (const bitmap of entry.levels) {
		if (bitmap) bitmap.close();
	}
	for (const m of entry.airMasks) if (m) m.close();
	pixelSceneCacheBytes -= entry.bytes;
	PIXEL_SCENE_BITMAP_CACHE.delete(entry.cacheKey);
	// No version bump: a bake that already holds the evicted scene's pixels
	// stays correct, and bumping here made every eviction a full rebuild.
}

export function clearPixelSceneBitmapCache() {
	for (const entry of [...PIXEL_SCENE_BITMAP_CACHE.values()]) releasePixelSceneEntry(entry);
	pixelSceneCacheBytes = 0;
	pendingSceneBitmaps.clear();
	deliveredSceneBitmaps.clear();
	sceneBitmapEpoch++;
	sceneBitmapVersion++;
}

// Under Render Everything the full-res textured instances of a whole overview
// view (~270 MB, more at 4K) do not fit the default budget, and evicting them
// only re-requests them next frame: the cache would thrash and never converge.
// Give the debug mode room instead.
function sceneBitmapBudgetBytes() {
	const budgetMB = appSettings.renderEverything
		? Math.max(appSettings.pixelSceneBitmapBudgetMB || 256, 2048) : (appSettings.pixelSceneBitmapBudgetMB || 256);
	return budgetMB * 1024 * 1024;
}

function evictPixelSceneBitmaps(keep) {
	const budget = sceneBitmapBudgetBytes();
	if (pixelSceneCacheBytes <= budget) return;
	const entries = [...PIXEL_SCENE_BITMAP_CACHE.values()].sort((a, b) => a.used - b.used);
	for (const entry of entries) {
		if (pixelSceneCacheBytes <= budget) break;
		if (entry === keep) continue; // never drop the one we are about to draw
		releasePixelSceneEntry(entry);
		sceneBitmapCounters.evictions++;
	}
}

function addPixelSceneBitmap(entry, level, bitmap) {
	const bytes = bitmap.width * bitmap.height * 4;
	entry.levels[level] = bitmap;
	entry.bytes += bytes;
	pixelSceneCacheBytes += bytes;
}

export function bitmapFromPixels(width, height, pixels) {
	const canvas = new OffscreenCanvas(width, height);
	const ctx = canvas.getContext('2d');
	const imageData = ctx.createImageData(width, height);
	imageData.data.set(pixels);
	ctx.putImageData(imageData, 0, 0);
	return canvas.transferToImageBitmap();
}

/**
 * The engine-faithful pixels for one stamped scene instance, or null when the
 * atlas/band tables are not loaded (or scene texturing is off).
 *
 * Runs the variant key the same way the overlay worker does -- material
 * substitutions first, in wang color space, so the texturing step still sees wang
 * colors -- but from the untouched base image and with the instance's own world
 * position, which is what the texture sampling needs.
 */
export function buildTexturedScenePixels(pixelScene, pixelSceneData, ignoreSettings = false) {
	// The worker builds on the main thread's say-so (it decided `textured` from
	// its own settings); its copy of the settings can lag a SYNC behind.
	if (!(ignoreSettings ? sceneTextureModules?.atlas.getMaterialAtlas() : sceneTextureAtlas())) return null;
	let pixels = pixelSceneData.imgElement;
	let biome = 'general';
	for (const part of (pixelScene.variantKey || '').split('&')) {
		const eq = part.indexOf('=');
		if (eq < 0) continue;
		if (part.slice(0, eq) === 'biome') biome = part.slice(eq + 1);
		else pixels = recolorPixelScene(pixels, parseInt(part.slice(0, eq), 16), parseInt(part.slice(eq + 1), 16));
	}
	return texturePixelSceneForBiome(pixelSceneData.name, pixels, pixelSceneData.width, pixelSceneData.height,
		biome, pixelScene.x, pixelScene.y);
}

// Source-over blend of a scene's visual-art override onto a COPY of its built
// pixels, restricted to painted-cell (alpha > 0) destination pixels. The visual may
// be smaller than the scene (hall_b/hall_br); both are anchored top-left.
export function overlayVisualArt(raw, width, height, art) {
	const out = new Uint8Array(raw.length);
	out.set(raw);
	const w = Math.min(width, art.width), h = Math.min(height, art.height);
	const s = art.data;
	for (let y = 0; y < h; y++) {
		for (let x = 0; x < w; x++) {
			const si = (y * art.width + x) * 4;
			const a = s[si + 3];
			if (a === 0) continue;
			const di = (y * width + x) * 4;
			if (out[di + 3] === 0) continue; // no cell here, art places none either
			if (a === 255) {
				// The art is the cell's color outright, so a translucent material
				// (glass texels are alpha 183) takes the art's opacity with it.
				out[di] = s[si]; out[di + 1] = s[si + 1]; out[di + 2] = s[si + 2]; out[di + 3] = 255;
			} else {
				const inv = 255 - a;
				out[di] = (s[si] * a + out[di] * inv + 127) / 255 | 0;
				out[di + 1] = (s[si + 1] * a + out[di + 1] * inv + 127) / 255 | 0;
				out[di + 2] = (s[si + 2] * a + out[di + 2] * inv + 127) / 255 | 0;
			}
		}
	}
	return out;
}

// Halve an image the way a cutout sprite wants to be halved: point sampling, but never
// losing coverage.
//
// Scene alpha is binary - a pixel is either painted material or air - and the seam
// between a scene and whatever it sits on is often one pixel thin. Averaging the 2x2
// block (a box filter) turns that seam into partial alpha, so the dark world behind
// shows through as a hairline crack along the scene edge; plain point sampling drops the
// seam outright and opens the same crack, wider. So the output takes the point sample
// (the block's lower-right pixel, which is what a nearest-neighbour downscale picks) and
// falls back to whichever of the other three is painted when that one is air. Painted
// area can only grow, never perforate, and alpha stays binary all the way down.
//
// Only the coverage is point-sampled: the color is the alpha-weighted average of the
// block's painted pixels. A point-sampled color bakes moire into every level of a
// regular pattern (brick walls), and averaging painted pixels alone opens no crack.
export function halveWithoutHoles(img) {
	const sw = img.width, sh = img.height, s = img.data;
	// Round up, so an odd-sized level keeps its last row/column instead of dropping it -
	// that trailing row is exactly the kind of one-pixel edge this reduction exists to keep.
	const w = Math.max(1, Math.ceil(sw / 2)), h = Math.max(1, Math.ceil(sh / 2));
	const out = { width: w, height: h, data: new Uint8ClampedArray(w * h * 4) };
	const d = out.data;
	for (let y = 0; y < h; y++) {
		const rowLo = Math.min(y * 2 + 1, sh - 1) * sw;
		const rowHi = y * 2 * sw;
		for (let x = 0; x < w; x++) {
			const colLo = Math.min(x * 2 + 1, sw - 1);
			const colHi = x * 2;
			let p = (rowLo + colLo) * 4;
			const b = (rowLo + colHi) * 4, c = (rowHi + colLo) * 4, e = (rowHi + colHi) * 4;
			if (s[p + 3] !== 255) {
				if (s[b + 3] > s[p + 3]) p = b;
				if (s[c + 3] > s[p + 3]) p = c;
				if (s[e + 3] > s[p + 3]) p = e;
			}
			const o = (y * w + x) * 4;
			// An odd trailing row/column reuses a pixel; counting it twice is harmless.
			const wa = s[p + 3] + s[b + 3] + s[c + 3] + s[e + 3];
			if (wa === 0) {
				d[o] = s[p]; d[o + 1] = s[p + 1]; d[o + 2] = s[p + 2];
			} else {
				const pa = s[p + 3], ba = s[b + 3], ca = s[c + 3], ea = s[e + 3];
				for (let k = 0; k < 3; k++) {
					d[o + k] = Math.round((s[p + k] * pa + s[b + k] * ba + s[c + k] * ca + s[e + k] * ea) / wa);
				}
			}
			d[o + 3] = s[p + 3];
		}
	}
	return out;
}

// Largest mip whose resolution still meets the on-screen resolution: at camera zoom z one
// world pixel covers z screen pixels, so a 1/2^L bitmap is enough while 2^-L >= z.
// Anything at or above 1:1 draws the native image, exactly as before.
export function pixelSceneMipLevel(z) {
	if (!(z > 0) || z >= 1) return 0;
	const level = Math.floor(Math.log2(1 / z));
	return level > PIXEL_SCENE_MAX_MIP ? PIXEL_SCENE_MAX_MIP : level;
}

