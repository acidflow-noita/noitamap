// Width and height are not actually needed here
export function recolorPixelScene(sourceData, sourceColor, targetColor) {
    const outData = new Uint8Array(sourceData.length);
	outData.set(sourceData);

	const sourceR = (sourceColor >> 16) & 0xFF;
	const sourceG = (sourceColor >> 8) & 0xFF;
	const sourceB = sourceColor & 0xFF;

	const targetR = (targetColor >> 16) & 0xFF;
	const targetG = (targetColor >> 8) & 0xFF;
	const targetB = targetColor & 0xFF;

    for (let i = 0; i < outData.length; i += 4) {
        const r = outData[i];
		const g = outData[i + 1];
		const b = outData[i + 2];
		if (r === sourceR && g === sourceG && b === sourceB) {
			outData[i] = targetR;
			outData[i + 1] = targetG;
			outData[i + 2] = targetB;
		}
    }

    return outData;
}

// 0xRRGGBB wang color -> compositing alpha, for materials drawn in a flat color
// (no texture): the XML color's alpha byte, as texturePixelSceneForBiome uses.
// Textured materials come from the caller (texturedFlatAlphas).
let flatWangAlpha = null;
function flatMaterialAlpha(rgb) {
	if (!flatWangAlpha) {
		flatWangAlpha = new Map();
		for (const m of MATERIAL_DATA) {
			if (m.texture || !m.wang || !m.color) continue;
			const a = (parseInt(m.color, 16) >>> 24) & 0xff;
			if (a < 255) flatWangAlpha.set(parseInt(m.wang, 16) & 0xffffff, a);
		}
	}
	return flatWangAlpha.get(rgb) ?? 255;
}

/**
 * The erase-aware variant of a flat (zoomed-out) scene build, for when the
 * terrain under it is the GL terrain that level 0's textured build erases.
 * Without it, zoomed out, a scene's air let the terrain fill its rooms and its
 * liquids (acid, water, blood) painted as opaque neon slabs.
 *
 * `wangPixels` is the scene after its material substitutions (still wang
 * colors); `flatPixels` is recolorPixelSceneForBiome's output for it. Mirrors
 * texturePixelSceneForBiome's air and translucency rules: FORCE AIR goes in the
 * mask unless the scene paints its air solid, and a translucent material keeps
 * its alpha and erases the terrain under it. `texturedAlphas` is
 * texturedFlatAlphas(): a textured material's alpha is its texels' mean. The density class stays flat -- its
 * per-cell band choice (which can answer air) is position-dependent, and this
 * build is shared by every instance.
 */
export function eraseFlatScenePixels(sceneName, wangPixels, flatPixels, targetBiome, texturedAlphas = []) {
	const airAlpha = sceneBiomePaint(sceneName, targetBiome).texturedAirAlpha;
	const texAlpha = new Map(texturedAlphas);
	const out = new Uint8Array(flatPixels);
	let airMask = null;
	for (let i = 0; i < wangPixels.length; i += 4) {
		if (wangPixels[i + 3] === 0) continue;
		const r = wangPixels[i], g = wangPixels[i + 1], b = wangPixels[i + 2];
		let a, erase;
		if (r === 0x00 && g === 0x00 && b === 0x42) {
			// A scene that paints its air solid leaves the terrain under it alone.
			a = airAlpha;
			erase = airAlpha === 0x00;
		} else {
			if (r === g && g === b) continue;
			const rgb = (r << 16) | (g << 8) | b;
			a = texAlpha.get(rgb) ?? flatMaterialAlpha(rgb);
			erase = a < 255;
		}
		out[i + 3] = a;
		if (erase) {
			if (!airMask) airMask = new Uint8Array(wangPixels.length);
			airMask[i + 3] = 0xff;
		}
	}
	return { pixels: out, airMask };
}
// ---------------------------------------------------------------------------
// Engine-faithful pixel scene texturing
//
// The game does not paint a stamped scene in flat material colors. Every cell it
// places gets its color from the material's materials_gfx texture, sampled at the
// cell's ABSOLUTE world coordinates with a negative-safe modulo
// (CellFactory_GetCellColor @0x007044a0) -- exactly the rule the GL terrain
// shader already reproduces for terrain. Two consequences for this module:
//
//  * the answer depends on where the scene landed, so a recolored variant can no
//    longer be shared by every instance of the same scene. The variant cache below
//    keeps doing what it is good at (material SUBSTITUTION, which is
//    position-independent), and the texturing happens per instance when its
//    bitmap is built.
//  * a scene's white/gray pixels are density 1.0 fed to the biome's
//    <MaterialComponent> bands, not a single flat color -- and the rare gates in
//    those bands are position-dependent too. band_select.js runs the engine's own
//    chooser for them.
//
// Both modules are pulled in dynamically so the overlay/search workers, which
// import this file for the flat recolor and the material lookups, never load the
// 270 KB engine tables or the material atlas.
// ---------------------------------------------------------------------------

let sceneTextureModules = null;   // { atlas: <material_atlas.js>, bands: <band_select.js> }
let sceneTextureLoading = null;

/** Starts (or joins) the one-time load of the atlas + band tables. Main thread. */
export function initPixelSceneTextures() {
	return sceneTextureLoading ??= (async () => {
		const [atlas, bands] = await Promise.all([
			import('./gl/material_atlas.js'),
			import('./engine_resolve/band_select.js'),
		]);
		await atlas.initMaterialAtlas();
		sceneTextureModules = { atlas, bands };
		return sceneTextureModules;
	})().catch((err) => {
		console.warn('[pixel scenes] material textures unavailable, staying on flat colors:', err);
		return null;
	});
}

/**
 * The loaded atlas when scene texturing is both enabled and ready, else null.
 *
 * Gated exactly as the GL terrain's own material textures are (app.js passes
 * `materialTextures && recolorMaterials` to the renderer), so the one toggle
 * moves scenes and terrain together and "material colors off" still means flat.
 */
function sceneTextureAtlas() {
	if (!appSettings.materialTextures || !appSettings.recolorMaterials || !sceneTextureModules) return null;
	return sceneTextureModules.atlas.getMaterialAtlas();
}

// 0xRRGGBB wang color -> material name, from MATERIAL_COLOR_LOOKUP's hex keys.
let wangColorToMaterial = null;
function materialForWangColor(rgb) {
	if (!wangColorToMaterial) {
		wangColorToMaterial = new Map();
		for (const [hex, name] of Object.entries(MATERIAL_COLOR_LOOKUP)) {
			wangColorToMaterial.set(parseInt(hex, 16) & 0xffffff, name);
		}
	}
	return wangColorToMaterial.get(rgb);
}

/**
 * The BIOME_ENGINE entry whose <MaterialComponent> bands answer this scene's
 * density class, preferring the scene's own folder biome and falling back to the
 * biome of the chunk it landed in (which is what a pseudo-biome folder means).
 * Only an entry that actually carries bands counts: the constant-material rooms
 * (temple_altar and friends) have an empty table and are answered by their
 * fillMaterial instead.
 *
 * Deliberately NOT gated on `biome.supported`. That flag is about the TOPOLOGY
 * resolve -- whether the carve branch, the inside-noise variant and the density
 * modifier of this biome are ported -- and a scene's density class runs none of
 * it: the coverage is a literal 1.0 that the caller feeds straight into
 * ComputeMaterialNoiseDensity. The band list is the only thing that has to be
 * complete, and it is: of the 174 biomes in the table exactly one (lava_90percent
 * #ffa717) loses a band to `unsupportedBand`, and it loses its only one, so the
 * `bands.length` test below already excludes it.
 *
 * Requiring `supported` cost the 41 biomes that carry bands but fail the topology
 * checks -- every orb room, every essence room, the gun/null/rock/song/moon rooms,
 * secret_lab, the pyramid interiors -- which are exactly the rooms whose entire
 * content is a stamped scene. They all fell back to a single flat fillMaterial.
 * Measured against the game on the orb room (groundtruth/batch3/orbroom, seed
 * 786433191): the flat fill matched 52.3% of the scene's 48,936 white pixels,
 * the band chooser matches 99.4% -- including the 17.9% that are AIR, which is
 * the orb room's background art showing through its floor.
 */
function densityBiomeFor(bands, targetBiome, underlyingBiome) {
	for (const name of [targetBiome, underlyingBiome]) {
		if (!name) continue;
		const conf = GENERATOR_CONFIG[name];
		if (!conf) continue;
		const biome = bands.engineBiomeForColor(conf.color & 0xffffff);
		// The NAME rides along so the hover readout can say which biome's bands
		// answered, which is the whole point of the pseudo-biome fallback.
		if (biome && biome.bands.length) return { entry: biome, biomeName: name };
	}
	return null;
}

/** The fillMaterial that answers a scene's density class where no band table does. */
function densityFillMaterialFor(targetBiome, underlyingBiome) {
	for (const name of [targetBiome, underlyingBiome]) {
		const conf = name ? GENERATOR_CONFIG[name] : null;
		const material = conf ? FILL_BIOME_MATERIALS[conf.color & 0xffffff] : undefined;
		if (material !== undefined) return { material, biomeName: name };
	}
	return null;
}

/**
 * The two biome names a variant key's `biome=` part carries: the scene's folder
 * biome and, after `@`, the biome of the chunk it landed in.
 */
function variantBiomes(variantKey) {
	let biome = 'general';
	for (const part of (variantKey || '').split('&')) {
		const eq = part.indexOf('=');
		if (eq >= 0 && part.slice(0, eq) === 'biome') biome = part.slice(eq + 1);
	}
	const at = biome.indexOf('@');
	return {
		targetBiome: at < 0 ? biome : biome.slice(0, at),
		underlyingBiome: at < 0 ? null : biome.slice(at + 1),
	};
}

/**
 * What a stamped scene's DENSITY CLASS -- its white/gray pixels, the engine's
 * "fill with this biome's own material" -- resolves to at one world pixel.
 *
 * The same lookup texturePixelSceneForBiome() runs per pixel while it builds an
 * instance, pulled out so the hover readout can answer for those pixels too
 * (js/utils.js getMaterialProvenanceAtWorldCoordinates). Without it the readout
 * walked the scene PNG, found a colour no material table knows, and reported
 * `Origin: air` over solid rock -- the blind spot that made the orb rooms look
 * empty while the renderer was painting them correctly.
 *
 * Returns null when nothing can answer (no bands loaded and no fill material).
 * `{ material: null, via: 'bands' }` is NOT that case: it means the band table
 * accepted nothing at density 1.0, which is a real AIR answer.
 *
 * @param {string} variantKey  the instance's variant key (only `biome=` is read)
 * @param {number} worldX      absolute world coordinates of the pixel
 * @param {number} worldY
 * @returns {{material: string|null, biomeName: string, via: 'bands'|'fill'}|null}
 */
export function sceneDensityClassAt(variantKey, worldX, worldY) {
	const { targetBiome, underlyingBiome } = variantBiomes(variantKey);
	// Gated exactly as the build is: with material textures off the scene paints
	// the flat fill colour, so claiming a band's answer would name a material the
	// picture on screen does not show.
	const bands = sceneTextureAtlas() ? sceneTextureModules.bands : null;
	const densityBiome = bands ? densityBiomeFor(bands, targetBiome, underlyingBiome) : null;
	if (densityBiome) {
		const id = bands.selectComponentForCell(densityBiome.entry, worldX, worldY,
			bands.computeMaterialNoiseDensity(worldX, worldY, 1.0));
		return { material: id < 0 ? null : bands.materialNameForId(id), biomeName: densityBiome.biomeName, via: 'bands' };
	}
	const fill = densityFillMaterialFor(targetBiome, underlyingBiome);
	return fill ? { material: fill.material, biomeName: fill.biomeName, via: 'fill' } : null;
}

/**
 * Per-instance engine-faithful build of one stamped pixel scene.
 *
 * `sourceData` is the scene PNG after its material substitutions (so its pixels
 * are still wang colors); (worldX, worldY) is where its top-left corner lands in
 * generation world space. Returns { pixels, airMask }: the RGBA image to draw,
 * and an RGBA mask that is opaque exactly on the scene's FORCE AIR pixels, or
 * null when it has none.
 *
 * Air (#000042) erases the world instead of painting it, so the caller draws the
 * mask with `destination-out` before the image. That is what makes air correct
 * over the engine-resolved GL terrain, which paints every chunk -- the old
 * "opaque background color over a fill biome" trick only covered the chunks
 * telescope itself filled.
 */
export function texturePixelSceneForBiome(sceneName, sourceData, width, height, targetBiome, worldX, worldY) {
	const { atlas: atlasMod, bands } = sceneTextureModules;
	const atlas = atlasMod.getMaterialAtlas();
	const recolorMaterials = appSettings.recolorMaterials;
	const paint = sceneBiomePaint(sceneName, targetBiome);
	const airAlpha = paint.texturedAirAlpha;
	const bgColorR = (paint.bgColor >> 16) & 0xFF;
	const bgColorG = (paint.bgColor >> 8) & 0xFF;
	const bgColorB = paint.bgColor & 0xFF;

	// The density class, resolved per pixel. A scene's gray pixels are fully solid
	// coverage, but the engine never hands raw coverage to the band chooser: it
	// runs it through ComputeMaterialNoiseDensity first, which warps the position
	// by a value-noise field and adds a simplex term. That is why a uniformly
	// white region comes out of the game as veins of several materials rather than
	// one flat answer, and it is the same call the GL terrain under the scene makes.
	const densityBiome = densityBiomeFor(bands, paint.targetBiome, paint.underlyingBiome);

	// How one material paints: its atlas rect when it has a texture, else its flat
	// display color (which is what the engine falls back to as well), composited
	// with the material's XML alpha (water 0xA0) exactly as the engine's cell
	// grid blends liquids/gasses over the background layer. Memoized -- a scene
	// uses a handful of materials across hundreds of thousands of pixels.
	const recipeByName = new Map();
	const recipeForMaterial = (name, fallbackFlat) => {
		let recipe = recipeByName.get(name);
		if (recipe === undefined) {
			const wang = MATERIAL_WANG_COLORS[name];
			recipe = {
				entry: atlasMod.materialAtlasEntry(atlas, name),
				flat: wang === undefined ? fallbackFlat : materialDisplayColor(name),
				alpha: wang === undefined ? 255 : atlasMod.materialAlpha(name),
			};
			recipeByName.set(name, recipe);
		}
		return recipe;
	};
	// The density class' answer where no band table covers it: the biome's own
	// fillMaterial, textured like any other material rather than flattened.
	const fillMaterial = densityFillMaterialFor(paint.targetBiome, paint.underlyingBiome);
	const fillRecipe = fillMaterial
		? recipeForMaterial(fillMaterial.material, paint.targetColor)
		: { entry: 0, flat: paint.targetColor, alpha: 255 };

	const densityRecipes = new Map();
	const densityRecipeFor = (id) => {
		let recipe = densityRecipes.get(id);
		if (recipe === undefined) {
			const name = id < 0 ? null : bands.materialNameForId(id);
			recipe = name ? recipeForMaterial(name, paint.targetColor) : fillRecipe;
			densityRecipes.set(id, recipe);
		}
		return recipe;
	};
	// Wang color -> the same recipe, via the material that owns the color.
	const wangRecipes = new Map();
	const wangRecipeFor = (rgb) => {
		let recipe = wangRecipes.get(rgb);
		if (recipe === undefined) {
			const name = materialForWangColor(rgb);
			recipe = name
				? recipeForMaterial(name, (recolorMaterials ? MATERIAL_COLOR_CONVERSION[rgb] : undefined) ?? rgb)
				: { entry: 0, flat: (recolorMaterials ? MATERIAL_COLOR_CONVERSION[rgb] : undefined) ?? rgb, alpha: 255 };
			wangRecipes.set(rgb, recipe);
		}
		return recipe;
	};

	const outData = new Uint8Array(sourceData.length);
	outData.set(sourceData);
	let airMask = null;

	for (let i = 0, p = 0; i < outData.length; i += 4, p++) {
		if (outData[i + 3] === 0) continue;   // untouched: alpha 0 / #000000
		const r = outData[i], g = outData[i + 1], b = outData[i + 2];

		// FORCE AIR: erases the world rather than painting it, so it goes in the
		// mask -- unless this scene is one of the few whose art wants its air
		// painted solid, in which case the image covers the same pixel and the mask
		// must leave it alone (that keeps the two passes disjoint, so the draw site
		// can run them in either order).
		if (r === 0x00 && g === 0x00 && b === 0x42) {
			if (airAlpha === 0x00) {
				if (!airMask) airMask = new Uint8Array(sourceData.length);
				airMask[i + 3] = 0xff;
			}
			outData[i] = bgColorR;
			outData[i + 1] = bgColorG;
			outData[i + 2] = bgColorB;
			outData[i + 3] = airAlpha;
			continue;
		}

		const wx = worldX + (p % width);
		const wy = worldY + ((p / width) | 0);

		// Full coverage through the biome's <MaterialComponent> bands for the gray
		// class; the wang color's own material for everything else.
		//
		// A band table that accepts nothing at density 1.0 answers AIR, and that is
		// a real answer rather than a gap: the orb room's floor is 17.9% air in the
		// game's own dump and the chooser predicts it (see densityBiomeFor). So a
		// -1 from a table we have goes into the erase mask exactly like FORCE AIR,
		// which is what lets a room's background art show through its own floor.
		// Only a biome with NO band table falls back to the flat fillMaterial.
		let recipe;
		if (r === g && g === b && r > 0) {
			if (densityBiome) {
				const id = bands.selectComponentForCell(densityBiome.entry, wx, wy,
					bands.computeMaterialNoiseDensity(wx, wy, 1.0));
				if (id < 0) {
					if (!airMask) airMask = new Uint8Array(sourceData.length);
					airMask[i + 3] = 0xff;
					outData[i + 3] = 0x00;
					continue;
				}
				recipe = densityRecipeFor(id);
			}
			else recipe = fillRecipe;
		}
		else recipe = wangRecipeFor((r << 16) | (g << 8) | b);
		const { entry, flat, alpha } = recipe;

		let a = alpha;
		if (entry > 0) {
			// Textured materials take the texel's own alpha (same rule as the GL
			// terrain shader); a fully transparent texel places no cell at all.
			const texel = atlasMod.materialTexelRGBA(atlas, entry, wx, wy);
			if (texel < 0) { outData[i + 3] = 0x00; continue; }
			a = (texel >>> 24) & 0xFF;
			outData[i] = (texel >> 16) & 0xFF;
			outData[i + 1] = (texel >> 8) & 0xFF;
			outData[i + 2] = texel & 0xFF;
		} else {
			outData[i] = (flat >> 16) & 0xFF;
			outData[i + 1] = (flat >> 8) & 0xFF;
			outData[i + 2] = flat & 0xFF;
		}
		if (a < 255) {
			// A translucent cell (liquid, gas) replaces the world cell under it
			// and blends over the BACKGROUND, so it must also erase the terrain:
			// mask first, translucent pixel second, background refilled behind by
			// the draw site's destination-over pass.
			outData[i + 3] = a;
			if (!airMask) airMask = new Uint8Array(sourceData.length);
			airMask[i + 3] = 0xff;
		}
	}

	return { pixels: outData, airMask };
}

// ---------------------------------------------------------------------------
// Scene material identity, for the edge-decal pass
//
// PixelScene_TryPaintEntry @0x00880fb0 runs its OWN EdgeGraphics pass after
// writing a scene's cells (BiomeMaterials_PaintEdgeMaterial @0x00721da0), so
// scene-painted materials get dressed exactly like generated terrain. That pass
// needs the material IDENTITY of every scene pixel, which is the same
// classification texturePixelSceneForBiome() runs for colors:
//   alpha 0 / #000000  -> untouched, the world cell under it stays
//   #000042            -> FORCE AIR, the world cell is removed
//   gray/white         -> density 1.0 through the biome's band chooser
//   anything else      -> the wang color's own material
//
// The gates are on material IDENTITY alone. A scene's _visual.png art overrides
// only the cell COLOR, never its material, so art cells participate in the edge
// decisions exactly like the material under them -- and the engine happily
// stamps over art at a real material border. The one thing that stops a scene's
// pass is `skip_edge_textures` (js/pixel_scene_edge_flags.js), which suppresses
// the restamp entirely while the scene's cells still erase the terrain pass.
// ---------------------------------------------------------------------------

/** The scene leaves this pixel alone; whatever cell the world has stays. */
export const SCENE_MAT_UNTOUCHED = -2;
/** A painted cell whose material the engine tables don't carry (prop art,
 *  unmapped wang colors). It blocks edges like any solid cell but can never
 *  stamp decals of its own. Large so it can live in an Int16Array beside
 *  real ids without colliding with them. */
export const SCENE_MAT_UNKNOWN = 0x7ffe;

/**
 * The per-pixel material ids one stamped scene instance paints, in the engine's
 * classification above. `bands` is the engine_resolve/band_select module (passed
 * in so this file keeps not importing the engine tables statically).
 *
 * Returns { grid: Int16Array, width, height, x, y, skipEdges } or null when the
 * scene's pixels aren't loaded. `skipEdges` is the game's `skip_edge_textures`:
 * the cells still erase the terrain stamps under them, but no restamp runs.
 */
export function pixelSceneMaterialGrid(scene, bands) {
	const data = PIXEL_SCENE_DATA[scene.key];
	if (!data || !ArrayBuffer.isView(data.imgElement)) return null;
	// Material substitutions first, in wang color space, exactly as the bitmap
	// build runs them; the biome part names the band table for the gray class.
	let pixels = data.imgElement;
	let biome = 'general';
	for (const part of (scene.variantKey || '').split('&')) {
		const eq = part.indexOf('=');
		if (eq < 0) continue;
		if (part.slice(0, eq) === 'biome') biome = part.slice(eq + 1);
		else pixels = recolorPixelScene(pixels, parseInt(part.slice(0, eq), 16), parseInt(part.slice(eq + 1), 16));
	}
	const at = biome.indexOf('@');
	const underlyingBiome = at < 0 ? null : biome.slice(at + 1);
	const targetBiome = at < 0 ? biome : biome.slice(0, at);
	const densityBiome = densityBiomeFor(bands, targetBiome, underlyingBiome);
	const fillMaterial = densityFillMaterialFor(targetBiome, underlyingBiome);
	const fillId = fillMaterial ? bands.materialIdForName(fillMaterial.material) : -1;

	const w = data.width, h = data.height;
	const grid = new Int16Array(w * h).fill(SCENE_MAT_UNTOUCHED);
	const wangIds = new Map();
	for (let p = 0, i = 0; p < w * h; p++, i += 4) {
		if (pixels[i + 3] === 0) continue;
		const r = pixels[i], g = pixels[i + 1], b = pixels[i + 2];
		if (r === 0x00 && g === 0x00 && b === 0x42) { grid[p] = 0; continue; }
		if (r === g && g === b && r > 0) {
			const wx = scene.x + (p % w), wy = scene.y + ((p / w) | 0);
			const id = densityBiome
				? bands.selectComponentForCell(densityBiome.entry, wx, wy,
					bands.computeMaterialNoiseDensity(wx, wy, 1.0))
				: -1;
			// Same rule the bitmap build paints: a table we have answering -1
			// is AIR (id 0), and only a biome with no table at all falls back
			// to its flat fill material.
			grid[p] = id >= 0 ? id
				: densityBiome ? 0
					: (fillId >= 0 ? fillId : SCENE_MAT_UNKNOWN);
			continue;
		}
		const rgb = (r << 16) | (g << 8) | b;
		let id = wangIds.get(rgb);
		if (id === undefined) {
			const name = materialForWangColor(rgb);
			id = name ? bands.materialIdForName(name) : -1;
			wangIds.set(rgb, id);
		}
		grid[p] = id >= 0 ? id : SCENE_MAT_UNKNOWN;
	}
	return {
		grid, width: w, height: h, x: scene.x, y: scene.y,
		skipEdges: !!data.skipEdgeTextures,
		// The colors-file coverage mask. The scene's edge pass is gated on it as
		// a whole (js/edge_decals.js sceneStampsAnyEdge), so the decal pass needs
		// it alongside the materials.
		artMask: data.artMask || null,
	};
}
