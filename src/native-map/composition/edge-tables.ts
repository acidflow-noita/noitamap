// Owned explicit-input edge tables. Preserves existing edges/data.ts arithmetic; see NOTICE.txt.
/**
 * Exact runtime tables for the optional compiled edge stamper.
 *
 * All rows are tightly packed. Integer views use native 32-bit words; C reads
 * color_argb as uint32_t, while the other words below are int32_t. Float64
 * views must start at an eight-byte-aligned address when copied into WASM.
 *
 * materialTable (12 bytes / material ID):
 *   struct Material { int32_t entry_start, entry_count, type_id; };
 * entryTable (28 bytes / entry), with entryPercent[entry] kept separately:
 *   struct Entry {
 *     int32_t type, overwrite, require_same_material, require_same_type;
 *     uint32_t color_argb;
 *     int32_t image_start, image_count;
 *   };
 * imageIndices contains the global image IDs referenced by each entry.
 * imageTable (28 bytes / global image ID):
 *   struct Image {
 *     int32_t atlas_x, atlas_y, width, height, min_angle, max_angle, flags;
 *   };
 * rayOx / rayOy contain the original length-five ray vectors. Sampling must
 * retain floor(local_coordinate + (ray_component / 5) * t), t = 1..4;
 * floor(ray_component / 5 * t) alone is not equivalent near cardinal rays.
 * normalAngles[hitMask] contains the result of the original normal routine
 * when exactly the rays selected by the 16-bit mask encounter an edge.
 * Mask zero maps to -1; all other masks preserve subtraction order, exact
 * zero handling, normalization, atan2, positive modulo, and degree scaling.
 *
 * Rays and angle values are generated by the consuming runtime's Math, not
 * serialized from Node. This keeps the original JavaScript implementation's
 * transcendental semantics when the experiment is hosted in a browser.
 * Tables are immutable to consumers and intended to be built once per worker.
 * Current tables plus the 414,720-byte RGBA atlas occupy less than 1 MiB.
 */

import {
  EDGE_ATLAS_HEIGHT,
  EDGE_ATLAS_WIDTH,
  EDGE_ENTRIES_BY_MATERIAL,
  EDGE_IMAGES,
  MATERIAL_TYPE_BY_NAME,
} from "./edge-data.mjs";
import { MATERIAL_NAMES_BY_ID } from "../complete-materials/engine-data.mjs";

export { EDGE_ATLAS_HEIGHT, EDGE_ATLAS_WIDTH };
export const MATERIAL_STRIDE = 3;
export const ENTRY_STRIDE = 7;
export const IMAGE_STRIDE = 7;
export const RAY_COUNT = 16;
export const NORMAL_ANGLE_COUNT = 1 << RAY_COUNT;
export const ATLAS_BYTE_LENGTH = EDGE_ATLAS_WIDTH * EDGE_ATLAS_HEIGHT * 4;

export const EDGE_TABLE_LAYOUT = Object.freeze({
  material: Object.freeze({
    stride: MATERIAL_STRIDE,
    bytes: MATERIAL_STRIDE * 4,
    entryStart: 0,
    entryCount: 1,
    typeId: 2,
  }),
  entry: Object.freeze({
    stride: ENTRY_STRIDE,
    bytes: ENTRY_STRIDE * 4,
    type: 0,
    overwrite: 1,
    requireSameMaterial: 2,
    requireSameType: 3,
    colorARGB: 4,
    imageStart: 5,
    imageCount: 6,
  }),
  image: Object.freeze({
    stride: IMAGE_STRIDE,
    bytes: IMAGE_STRIDE * 4,
    atlasX: 0,
    atlasY: 1,
    width: 2,
    height: 3,
    minAngle: 4,
    maxAngle: 5,
    flags: 6,
  }),
});

type EdgeEntry = readonly [
  number,
  number,
  number,
  number,
  number,
  number,
  readonly number[],
];

/** Construct C-compatible immutable tables in this JavaScript runtime. */
function emptyEdgeTables() {
  const materialCount = MATERIAL_NAMES_BY_ID.length;
  const materialTable = new Int32Array(materialCount * MATERIAL_STRIDE);
  const entries: number[] = [];
  const percentages: number[] = [];
  const indices: number[] = [];

  for (let id = 0; id < materialCount; id++) {
    const name = MATERIAL_NAMES_BY_ID[id];
    const materialEntries =
      (name &&
        (
          EDGE_ENTRIES_BY_MATERIAL as unknown as Record<
            string,
            readonly EdgeEntry[]
          >
        )[name]) ||
      [];
    const base = id * MATERIAL_STRIDE;
    materialTable[base] = percentages.length;
    materialTable[base + 1] = materialEntries.length;
    materialTable[base + 2] =
      (MATERIAL_TYPE_BY_NAME as Record<string, number>)[name] ?? 0;
    for (const entry of materialEntries) {
      const [type, percent, overwrite, sameMaterial, sameType, color, images] =
        entry;
      entries.push(
        type,
        overwrite,
        sameMaterial,
        sameType,
        color | 0,
        indices.length,
        images.length,
      );
      percentages.push(percent);
      indices.push(...images);
    }
  }

  const entryTable = Int32Array.from(entries);
  const entryPercent = Float64Array.from(percentages);
  const imageIndices = Int32Array.from(indices);
  const imageTable = new Int32Array(EDGE_IMAGES.length * IMAGE_STRIDE);
  for (let i = 0; i < EDGE_IMAGES.length; i++) {
    const image = EDGE_IMAGES[i];
    if (
      image.length !== IMAGE_STRIDE ||
      image.some((value) => !Number.isInteger(value))
    ) {
      throw new Error(
        `Edge image ${i} cannot be represented by the integer descriptor layout`,
      );
    }
    imageTable.set(image, i * IMAGE_STRIDE);
  }

  // Keep these expressions in the same order as edge_decals.js. In particular,
  // calculating unit vectors first and multiplying later is not equivalent.
  const rayOx = new Float64Array(RAY_COUNT);
  const rayOy = new Float64Array(RAY_COUNT);
  for (let i = 0; i < RAY_COUNT; i++) {
    const angle = i * (Math.PI / 8);
    rayOx[i] = -5 * Math.sin(angle);
    rayOy[i] = 5 * Math.cos(angle);
  }

  const normalAngles = new Float64Array(NORMAL_ANGLE_COUNT);
  normalAngles[0] = -1;

  const buffers = {
    materialTable,
    entryTable,
    entryPercent,
    imageIndices,
    imageTable,
    rayOx,
    rayOy,
    normalAngles,
  };
  const byteLength = Object.values(buffers).reduce(
    (total, view) => total + view.byteLength,
    0,
  );
  return {
    ...buffers,
    materialCount,
    entryCount: entryPercent.length,
    imageCount: EDGE_IMAGES.length,
    byteLength,
  };
}

function fillAngles(
  tables: ReturnType<typeof emptyEdgeTables>,
  from: number,
  to: number,
) {
  const { rayOx, rayOy, normalAngles } = tables;
  const twoPi = Math.PI * 2;
  const degrees = 180 / Math.PI;
  for (let hitMask = from; hitMask < to; hitMask++) {
    let sumX = 0;
    let sumY = 0;
    // A subset-sum recurrence can change floating-point addition order; the
    // fixed original ray order is necessary even for nominally symmetric hits.
    for (let i = 0; i < RAY_COUNT; i++) {
      if (!(hitMask & (1 << i))) continue;
      sumX -= rayOx[i];
      sumY -= rayOy[i];
    }
    const length = Math.sqrt(sumX * sumX + sumY * sumY);
    if (length === 0) {
      normalAngles[hitMask] = 0;
      continue;
    }
    const angle = Math.atan2(sumY / length, sumX / length);
    normalAngles[hitMask] = (((angle % twoPi) + twoPi) % twoPi) * degrees;
  }
}
export function buildEdgeTables() {
  const tables = emptyEdgeTables();
  fillAngles(tables, 1, NORMAL_ANGLE_COUNT);
  return tables;
}
/** Give optional initialization a task boundary between bounded table batches. */
export async function buildEdgeTablesAsync() {
  const tables = emptyEdgeTables();
  for (let from = 1; from < NORMAL_ANGLE_COUNT; from += 4096) {
    await new Promise<void>((resolve) => setTimeout(resolve, 0));
    fillAngles(tables, from, Math.min(from + 4096, NORMAL_ANGLE_COUNT));
  }
  return tables;
}
